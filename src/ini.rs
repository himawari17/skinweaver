use anyhow::{Context, Result};
use std::{fmt, fs, path::Path};

#[derive(Clone, Debug, Default, PartialEq)]
pub struct Section {
    pub name: String,
    pub values: Vec<(String, String)>,
}

impl Section {
    pub fn get(&self, key: &str) -> Option<&str> {
        self.values
            .iter()
            .find(|(k, _)| k.eq_ignore_ascii_case(key))
            .map(|(_, v)| v.as_str())
    }
    pub fn set(&mut self, key: &str, value: impl Into<String>) {
        self.remove(key);
        self.values.push((key.into(), value.into()));
    }
    pub fn remove(&mut self, key: &str) {
        self.values.retain(|(k, _)| !k.eq_ignore_ascii_case(key));
    }
}

#[derive(Clone, Debug, Default, PartialEq)]
pub struct SkinIni {
    pub sections: Vec<Section>,
}

impl SkinIni {
    pub fn new(name: &str) -> Self {
        let mut ini = Self::default();
        ini.set("General", "Name", name);
        ini.set("General", "Author", "Skinweaver");
        ini.set("General", "Version", "latest");
        ini
    }

    pub fn parse(text: &str) -> Self {
        let mut ini = Self::default();
        for line in text.trim_start_matches('\u{feff}').lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with([';', '#']) || line.starts_with("//") {
                continue;
            }
            let line = line.split(" //").next().unwrap_or(line).trim();
            if line.starts_with('[')
                && let Some(end) = line.find(']')
            {
                ini.sections.push(Section {
                    name: line[1..end].trim().into(),
                    values: vec![],
                });
                continue;
            }
            if let Some((key, value)) = line.split_once(':') {
                let key = key.trim();
                if let Some(section) = ini.sections.last_mut()
                    && !key.is_empty()
                    && section.get(key).is_none()
                {
                    section.values.push((key.into(), value.trim().into()));
                }
            }
        }
        ini
    }

    pub fn read(path: &Path) -> Result<Self> {
        let bytes = fs::read(path).with_context(|| format!("Read {}", path.display()))?;
        let text = if bytes.starts_with(&[0xff, 0xfe]) {
            encoding_rs::UTF_16LE.decode(&bytes).0.into_owned()
        } else if bytes.starts_with(&[0xfe, 0xff]) {
            encoding_rs::UTF_16BE.decode(&bytes).0.into_owned()
        } else {
            String::from_utf8(bytes.clone())
                .unwrap_or_else(|_| encoding_rs::WINDOWS_1251.decode(&bytes).0.into_owned())
        };
        Ok(Self::parse(&text))
    }

    pub fn get(&self, section: &str, key: &str) -> Option<&str> {
        self.sections
            .iter()
            .find(|s| s.name.eq_ignore_ascii_case(section))?
            .get(key)
    }
    pub fn section_mut(&mut self, name: &str) -> &mut Section {
        let index = self
            .sections
            .iter()
            .position(|s| s.name.eq_ignore_ascii_case(name))
            .unwrap_or_else(|| {
                self.sections.push(Section {
                    name: name.into(),
                    values: vec![],
                });
                self.sections.len() - 1
            });
        &mut self.sections[index]
    }
    pub fn set(&mut self, section: &str, key: &str, value: impl Into<String>) {
        self.section_mut(section).set(key, value);
    }
    pub fn colors(&self) -> Vec<[u8; 3]> {
        let colors: Vec<_> = (1..=8)
            .filter_map(|n| {
                let values: Vec<_> = self
                    .get("Colours", &format!("Combo{n}"))?
                    .split(',')
                    .map(|s| s.trim().parse::<u8>())
                    .collect();
                if values.len() != 3 {
                    return None;
                }
                Some([
                    *values[0].as_ref().ok()?,
                    *values[1].as_ref().ok()?,
                    *values[2].as_ref().ok()?,
                ])
            })
            .collect();
        if colors.is_empty() {
            vec![[255, 192, 0], [0, 202, 0], [18, 124, 255], [242, 24, 57]]
        } else {
            colors
        }
    }
}

impl fmt::Display for SkinIni {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        writeln!(f, "// Generated by Skinweaver\n")?;
        for section in &self.sections {
            writeln!(f, "[{}]", section.name)?;
            for (key, value) in &section.values {
                writeln!(f, "{key}: {value}")?;
            }
            writeln!(f)?;
        }
        Ok(())
    }
}

pub fn property_has_path(key: &str) -> bool {
    (key.starts_with("Stage") && key != "StageSeparation")
        || key.ends_with("Prefix")
        || key.starts_with("KeyImage")
        || key.starts_with("NoteImage")
        || matches!(
            key,
            "LightingN"
                | "LightingL"
                | "WarningArrow"
                | "Hit0"
                | "Hit50"
                | "Hit100"
                | "Hit200"
                | "Hit300"
                | "Hit300g"
        )
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn repeated_mania_sections_and_values_roundtrip() {
        let ini = SkinIni::parse(
            "\u{feff}// hi\n[General]\nName: [Skin]: test\nName: duplicate\nAuthor: https://example.org\n[Mania]\nKeys: 4\nNoteImage0: folder\\note\n[Mania]\nKeys: 7 // comment\n",
        );
        assert_eq!(ini.get("General", "Name"), Some("[Skin]: test"));
        assert_eq!(ini.get("General", "Author"), Some("https://example.org"));
        assert_eq!(ini.sections[2].get("Keys"), Some("7"));
        assert_eq!(ini, SkinIni::parse(&ini.to_string()));
    }
    #[test]
    fn malformed_colors_fall_back() {
        let ini = SkinIni::parse("[Colours]\nCombo1: 1,2\nCombo2: a,0,0\nCombo3: 300,0,0");
        assert_eq!(ini.colors().len(), 4);
    }
}
